package JavaPractice;

public class ComparatorEmployee {

    int empid;
    String empname;
    int age;

    public ComparatorEmployee(int empid, String empname, int age) {
        this.empid = empid;
        this.empname = empname;
        this.age = age;
    }

    public int getEmpid() {
        return empid;
    }

    public String getEmpname() {
        return empname;
    }

    public int getEmpage() {
        return age;
    }

}
